# Lista é uma estrutura indexada
# Índices  0  1  2  3
numeros = [1, 2, 3, 4]
print(numeros)

frutas = ["maça", "banana", "laranja"]
print(frutas)

misto = [1, True, 3.14, "João", [1, 2, 3]]
print(misto)

matriz = [[1, 2, 3], [4, 5, 6], [7, 8, 9]]
print(matriz)

# Acessar os elementos pelo índice
print(numeros[3])
print(frutas[1])
print(misto[4][1])

# Acessando a lista do fim para o início, usa-se é valor negativo
print(frutas[-1])
